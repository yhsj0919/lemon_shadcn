import 'package:flutter/material.dart' show Icons;
import 'package:shadcn_flutter/shadcn_flutter.dart' as shad;

/// Lucide icon font constants from upstream `shadcn_flutter`.
///
/// ```dart
/// Icon(AppLucideIcons.plus)
/// ```
typedef AppLucideIcons = shad.LucideIcons;

/// Radix icon font constants from upstream `shadcn_flutter`.
///
/// ```dart
/// Icon(AppRadixIcons.chevronDown)
/// ```
typedef AppRadixIcons = shad.RadixIcons;

/// Bootstrap icon font constants from upstream `shadcn_flutter`.
///
/// ```dart
/// Icon(AppBootstrapIcons.alarm)
/// ```
typedef AppBootstrapIcons = shad.BootstrapIcons;

/// Material [Icons] alias so Material-first pages can stay on the App surface.
///
/// ```dart
/// Icon(AppMaterialIcons.add)
/// ```
typedef AppMaterialIcons = Icons;
